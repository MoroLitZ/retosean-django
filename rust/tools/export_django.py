def _plain(text):
    decomposed = unicodedata.normalize("NFKD", text)
    return "".join(c for c in decomposed if not unicodedata.combining(c)).casefold()

_DISPLAY_BY_PLAIN = {_plain(t): t for t in DISPLAY_TEXT}

def display(text):
    """Return the correctly accented Spanish form of an exported display string."""
    text = str(text)
    text = DISPLAY_REWORDED.get(text, text)
    return _DISPLAY_BY_PLAIN.get(_plain(text), text)

def export():
    (OUT / "sql").mkdir(exist_ok=True)
    # Collect DDL without executing it or modifying the configured database.
    with connection.schema_editor(collect_sql=True, atomic=False) as editor:
        for model in apps.get_models():
            editor.create_model(model)
    (OUT / "sql/schema.sql").write_text("\n".join(editor.collected_sql + column_defaults()), encoding="utf-8")
    types = {"BooleanField": "bool", "DateField": "chrono::NaiveDate", "DateTimeField": "chrono::DateTime<chrono::Utc>",
             "TimeField": "chrono::NaiveTime", "DecimalField": "rust_decimal::Decimal", "UUIDField": "uuid::Uuid",
             "JSONField": "serde_json::Value", "FloatField": "f64", "DurationField": "i64"}
    schema, code = [], ["// Generated by tools/export_django.py; typed PostgreSQL domain records.", "use serde::{Deserialize, Serialize};"]
    for model in MODELS:
        fields = []
        code += ["#[derive(Debug, Clone, Serialize, Deserialize)]", f"pub struct {model.__name__} {{"]
        for f in model._meta.fields:
            kind = f.get_internal_type()
            ty = types.get(kind, "i64" if "Integer" in kind or kind in ("AutoField", "BigAutoField", "ForeignKey", "OneToOneField") else "String")
            if f.null:
                ty = f"Option<{ty}>"
            name = f.attname
            if name == "password":
                code.append("    #[serde(skip_serializing)]")
            code.append(f"    pub {('r#' + name) if name in ('type', 'ref', 'match') else name}: {ty},")
            fields.append({"name": name, "verbose_name": str(f.verbose_name), "type": kind, "related_table": f.related_model._meta.db_table if f.is_relation else None, "null": f.null, "max_length": f.max_length, "choices": [[k, str(v)] for k, v in (f.choices or [])]})
        code += ["}", ""]
        schema.append({"name": model.__name__, "app": model._meta.app_label, "table": model._meta.db_table,
                       "verbose_name": str(model._meta.verbose_name), "verbose_name_plural": str(model._meta.verbose_name_plural), "fields": fields})
    (OUT / "src/models.rs").write_text("\n".join(code), encoding="utf-8")
    (OUT / "schema.json").write_text(json.dumps(schema, ensure_ascii=False, indent=2), encoding="utf-8")
    # Live MaquinaEstados objects (services.py and cierre/views.py): transitions,
    # plus the Spanish name and labels Django uses in TransicionInvalida messages.
    import importlib
    from apps.seguimiento.services import MaquinaEstados
    machines, meta = {}, {}
    modules = [f"apps.{p.parent.name}.services" for p in sorted((ROOT / "apps").glob("*/services.py"))] + ["apps.cierre.views"]
    for module in modules:
        for name, value in vars(importlib.import_module(module)).items():
            if isinstance(value, MaquinaEstados) and name.startswith("MAQUINA_"):
                machines[name] = {k: sorted(v) for k, v in value.transiciones.items()}
                meta[name] = {"nombre": display(value.nombre), "etiquetas": {k: display(v) for k, v in value.etiquetas.items()}}
    (OUT / "states_meta.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2, sort_keys=True), encoding="utf-8")
    (OUT / "states.json").write_text(json.dumps(machines, ensure_ascii=False, indent=2), encoding="utf-8")
    from apps.notificaciones.eventos import EVENTOS
    eventos = {e.slug: {"tipo": e.tipo, "titulo": display(e.titulo), "permite_email": e.permite_email} for e in EVENTOS.values()}
    (OUT / "events.json").write_text(json.dumps(eventos, ensure_ascii=False, indent=2, sort_keys=True), encoding="utf-8")
    export_seed()
    print(f"Exported {len(MODELS)} models and {len(machines)} state machines; no database writes.")

def column_defaults():
    """Django keeps most defaults in Python, so raw SQL inserts from Rust would
    fail on every NOT NULL column added later. Mirror them as database defaults."""
    sql = []
    for model in MODELS:
        for f in model._meta.local_fields:
            if f.null or f.primary_key or f.is_relation:
                continue
            kind = f.get_internal_type()
            if getattr(f, "auto_now", False) or getattr(f, "auto_now_add", False):
                literal = "now()" if kind == "DateTimeField" else "CURRENT_DATE"
            elif f.has_default() and not callable(f.default):
                value = f.default
                if isinstance(value, bool):
                    literal = "true" if value else "false"
                elif isinstance(value, (int, float, decimal.Decimal)):
                    literal = str(value)
                elif isinstance(value, str):
                    literal = "'" + value.replace("'", "''") + "'"
                else:
                    continue
            elif f.has_default() and kind == "JSONField":
                literal = "'" + json.dumps(f.get_default()).replace("'", "''") + "'::jsonb"
            elif f.has_default() and kind == "DateTimeField":
                literal = "now()"
            elif kind in ("CharField", "TextField", "EmailField", "URLField", "SlugField", "FileField", "ImageField") and f.blank:
                literal = "''"
            else:
                continue
            sql.append(f'ALTER TABLE "{model._meta.db_table}" ALTER COLUMN "{f.column}" SET DEFAULT {literal};')
    return sql


def export_seed():
    statements = []
    def quote(value):
        if value is None: return "NULL"
        if value is True: return "TRUE"
        if value is False: return "FALSE"
        if isinstance(value, (int, float, decimal.Decimal)): return str(value)
        if isinstance(value, (dict, list)): value = json.dumps(value)
        return "'" + str(value).replace("'", "''") + "'"
    def row(label, **values):
        model = apps.get_model(label)
        cols, vals = [], []
        for f in model._meta.fields:
            name = f.attname
            cols.append('"' + f.column + '"')
            if name in values: val = values[name]
            elif f.null: val = None
            elif f.get_internal_type() == "DateTimeField" and callable(f.default):
                # Callable defaults (timezone.now) would make each export differ.
                vals.append("CURRENT_TIMESTAMP"); continue
            elif f.has_default(): val = f.get_default()
            elif f.get_internal_type() == "BooleanField": val = False
            elif f.get_internal_type() in ("DateField", "DateTimeField"):
                vals.append("CURRENT_DATE" if f.get_internal_type() == "DateField" else "CURRENT_TIMESTAMP"); continue
            elif f.get_internal_type() == "JSONField": val = []
            elif "Integer" in f.get_internal_type() or f.get_internal_type() == "DecimalField": val = 0
            else: val = ""
            vals.append(quote(val))
